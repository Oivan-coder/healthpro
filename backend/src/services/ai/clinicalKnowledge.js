function normalize(value) {
  return String(value || "").toLowerCase().replace(/ё/g, "е").trim();
}

function findGroup(context = {}) {
  const haystack = normalize(`${context.test_code || ""} ${context.test_name || ""}`);
  return GROUPS.find(group => group.patterns.some(pattern => pattern.test(haystack))) || null;
}

function sourceList(group) {
  const sources = [SOURCE_CATALOG.minzdrav, SOURCE_CATALOG.helix, SOURCE_CATALOG.loinc];
  return sources.map(source => ({ ...source }));
}

function referenceText(context = {}) {
  const low = context.reference_low ?? context.referenceLow ?? context.ref_low ?? null;
  const high = context.reference_high ?? context.referenceHigh ?? context.ref_high ?? null;
  const unit = context.unit ? ` ${context.unit}` : "";
  if (low !== null && high !== null) return `${low}–${high}${unit}`;
  if (low !== null) return `от ${low}${unit}`;
  if (high !== null) return `до ${high}${unit}`;
  return context.reference || context.reference_text || context.referenceText || "";
}

function knowledgeFor(context = {}) {
  const group = findGroup(context);
  if (!group) return null;
  const direction = context.flag === "low" ? "low" : context.flag === "high" ? "high" : null;
  return {
    groupId: group.id,
    groupTitle: group.title,
    interpretation: direction ? group[direction] : "Показатель оценивают в контексте референсного диапазона, динамики и связанных лабораторных данных.",
    related: [...group.related],
    documents: group.documents.map(document => ({ ...document })),
    sources: sourceList(group),
    reference: referenceText(context)
  };
}

function missingRelated(knowledge, patientLabs = []) {
  if (!knowledge) return [];
  const available = normalize(patientLabs.map(lab => `${lab.name || ""} ${lab.code || ""}`).join(" | "));
  return knowledge.related.filter(name => !available.includes(normalize(name).split("/")[0]));
}

module.exports = {
  SOURCE_CATALOG,
  GROUPS,
  findGroup,
  knowledgeFor,
  missingRelated,
  referenceText
};
